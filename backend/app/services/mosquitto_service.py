"""Mosquitto Provisioning and Per-Node ACL Configuration Service.

Generates and maintains VeyraSense-owned Mosquitto files in the persistent directory
(e.g., /var/lib/veyrasense/mosquitto/):
1. mosquitto_passwd: User authentication file with PBKDF2-HMAC-SHA512 ($7$) password hashes.
   Plaintext passwords are strictly forbidden.
2. mosquitto.acl: Strict per-node topic access control lists enforcing least privilege.
3. veyrasense.conf: Dedicated listener configuration on port 1884, isolated from CARES-RX (port 1883).

Coexistence Architecture:
- CARES-RX retains listener port 1883 and /etc/mosquitto/passwd completely untouched.
- VeyraSense operates on listener port 1884 using 'per_listener_settings true'.
- VeyraSense never reads, writes, merges into, or regenerates /etc/mosquitto/passwd.
"""
import logging
from pathlib import Path
from typing import List
from sqlalchemy.orm import Session
from app.core.config import settings
from app.core.security import hash_mosquitto_password
from app.database.models.node import SensorNode

logger = logging.getLogger("mosquitto_service")


class MosquittoProvisioningService:
    """Manages Mosquitto configuration, authentication, and per-node ACLs for VeyraSense."""

    @staticmethod
    def sync_mosquitto_configuration(db: Session) -> dict[str, str]:
        """Regenerate Mosquitto configuration, password file, and ACLs based on current DB state.
        
        Only modifies VeyraSense-owned files inside settings.resolved_mosquitto_dir.
        Existing broker configuration, CARES-RX listener (port 1883), and /etc/mosquitto/passwd
        are strictly preserved.
        """
        mosquitto_dir = settings.resolved_mosquitto_dir

        # 1. Fetch all active, non-revoked nodes with MQTT credentials
        nodes = (
            db.query(SensorNode)
            .filter(
                SensorNode.is_active.is_(True),
                SensorNode.provisioning_status != "revoked",
                SensorNode.mqtt_username.isnot(None),
                SensorNode.mqtt_password_hash.isnot(None),
            )
            .all()
        )

        # 2. Build mosquitto.acl for VeyraSense listener
        acl_lines: List[str] = [
            "# =====================================================================",
            "# VeyraSense Mosquitto Per-Node Topic Access Control List (ACL)",
            f"# Target: Isolated Listener Port {settings.MQTT_BROKER_PORT}",
            "# Auto-generated by VeyraSense Backend Provisioning Service",
            "# Strict Principle of Least Privilege: Nodes CANNOT spoof other nodes",
            "# =====================================================================",
            "",
            "# Backend Ingestion & Supervision Service (Internal)",
            f"user {settings.MQTT_BACKEND_USERNAME}",
            "topic read veyrasense/nodes/+/telemetry",
            "topic readwrite veyrasense/nodes/+/status",
            "topic write veyrasense/nodes/+/commands",
            "",
        ]

        # 3. Build mosquitto_passwd
        # IMPORTANT: Plaintext passwords are NEVER written to password files.
        # Backend password is consistently hashed using Mosquitto $7$ PBKDF2-HMAC-SHA512.
        backend_hash = hash_mosquitto_password(settings.MQTT_BACKEND_PASSWORD)
        passwd_lines: List[str] = [
            f"# =====================================================================",
            f"# VeyraSense Mosquitto Authentication File ({len(nodes) + 1} users)",
            f"# Target: Isolated Listener Port {settings.MQTT_BROKER_PORT}",
            f"# Auto-generated by VeyraSense Backend Provisioning Service",
            f"# Hashed using PBKDF2-HMAC-SHA512 ($7$); plaintext forbidden",
            f"# =====================================================================",
            f"{settings.MQTT_BACKEND_USERNAME}:{backend_hash}",
        ]

        for node in nodes:
            username = node.mqtt_username or node.node_id
            pw_hash = node.mqtt_password_hash or ""

            # Ensure valid $7$ PBKDF2 hash format
            if not pw_hash.startswith("$7$"):
                pw_hash = hash_mosquitto_password(pw_hash)
                node.mqtt_password_hash = pw_hash

            # Per-node ACL entry
            acl_lines.extend([
                f"# --- Node: {node.node_id} ({node.name}) ---",
                f"user {username}",
                f"topic write veyrasense/nodes/{node.node_id}/telemetry",
                f"topic readwrite veyrasense/nodes/{node.node_id}/status",
                f"topic read veyrasense/nodes/{node.node_id}/commands",
                "",
            ])

            # Password entry
            passwd_lines.append(f"{username}:{pw_hash}")

        # Commit any re-hashed passwords
        db.commit()

        # 4. Build isolated listener configuration (No duplicate global directives)
        conf_content = f"""# ==============================================================================
# VeyraSense Edge Gateway — Isolated Mosquitto Listener Configuration
# Port {settings.MQTT_BROKER_PORT} (Dedicated to VeyraSense, isolated from CARES-RX on Port 1883)
# Auto-generated by VeyraSense Backend Provisioning Service
# ==============================================================================

listener {settings.MQTT_BROKER_PORT}
allow_anonymous false
password_file {settings.mosquitto_passwd_path.as_posix()}
acl_file {settings.mosquitto_acl_path.as_posix()}
"""

        # Write files atomically within VeyraSense persistent directory
        acl_path = settings.mosquitto_acl_path
        passwd_path = settings.mosquitto_passwd_path
        conf_path = settings.mosquitto_conf_path

        acl_path.write_text("\n".join(acl_lines) + "\n", encoding="utf-8")
        passwd_path.write_text("\n".join(passwd_lines) + "\n", encoding="utf-8")
        conf_path.write_text(conf_content, encoding="utf-8")

        # Set restrictive permissions if on POSIX filesystem
        try:
            passwd_path.chmod(0o640)
            acl_path.chmod(0o640)
            conf_path.chmod(0o640)
        except Exception:
            pass

        logger.info(
            f"Synced VeyraSense Mosquitto config with {len(nodes)} active nodes. "
            f"Port: {settings.MQTT_BROKER_PORT}, ACL: {acl_path}, Passwd: {passwd_path}"
        )

        return {
            "acl_file": str(acl_path),
            "passwd_file": str(passwd_path),
            "conf_file": str(conf_path),
            "active_nodes_provisioned": len(nodes),
        }
